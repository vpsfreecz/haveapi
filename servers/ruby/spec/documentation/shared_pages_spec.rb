require 'spec_helper'
require 'rack/mock'

RSpec.describe HaveAPI::SharedDocumentationHelpers do
  api do
    define_resource(:Widget) do
      version 1
      auth false

      define_action(:Index, superclass: HaveAPI::Actions::Default::Index) do
        authorize { allow }
      end
    end

    define_resource(:OtherWidget) do
      version 2
      auth false

      define_action(:Index, superclass: HaveAPI::Actions::Default::Index) do
        authorize { allow }
      end
    end
  end

  default_version 1

  def json_element(body, name)
    JSON.parse(body.match(%r{<script[^>]*#{name}[^>]*>(.*?)</script>}m)[1])
  end

  def expect_neutral_shell(body, page)
    expect(body).to include('data-docs', "data-page=\"#{page}\"", 'data-resource=""',
                            'id="docs-main"', '/js/documentation.js', '/css/documentation.css',
                            'Generated by')
    expect(body).not_to include('/js/main.js', '/js/jquery', '/css/bootstrap', 'data-resource-nav',
                                'data-language-select', 'data-documentation-login', 'docs-identity', 'docs-visibility-note',
                                'class="docs-sign-in', 'class="authentication"')
    expect(body).to include('<details data-documentation-menu>', 'data-documentation-menu-content')
    expect(body).not_to include('data-theme-menu', 'data-account-menu')
    expect(json_element(body, 'data-documentation-clients')).to eq([])
    expect(json_element(body, 'data-legacy-anchors')).to eq({})
    %w[auto light dark].each do |theme|
      expect(body).to include("data-theme-choice=\"#{theme}\"")
    end
  end

  it 'keeps root discovery once and renders its existing versions in the common shell' do
    app
    server = instance_variable_get(:@api)
    allow(server).to receive(:describe).and_call_original

    get '/'

    expect(last_response).to be_ok
    expect(last_response.headers['Cache-Control']).to eq('private, no-store')
    expect(last_response.body).to include('<h1>API versions</h1>', 'href="/v1/"', 'href="/v2/"',
                                          'Version 1', 'Version 2', '(default)', '<title>API versions')
    main = last_response.body.match(%r{<main\b[^>]*>(.*?)</main>}m)[1]
    expect(main.scan(/<h1\b/).length).to eq(1)
    expect(main).not_to include('API description', 'Available versions:')
    expect_neutral_shell(last_response.body, 'versions')
    expect(server).to have_received(:describe).once
  end

  {
    '/doc' => 'Server-side implementation',
    '/doc/index' => 'Server-side implementation',
    '/doc/index.md' => 'Server-side implementation',
    '/doc/readme' => 'HaveAPI',
    '/doc/protocol' => 'Protocol definition',
    '/doc/protocol.md' => 'Protocol definition',
    '/doc/create-client' => 'Client definition',
    '/doc/create-client.md' => 'Client definition',
    '/doc/client-examples' => 'Client examples',
    '/doc/client-examples.md' => 'Client examples',
    '/doc/json-schema' => 'Envelope'
  }.each do |path, heading|
    it "serves #{path} in the neutral shell without API discovery or cookie authentication" do
      app
      server = instance_variable_get(:@api)
      allow(server).to receive(:describe).and_call_original
      allow(server).to receive(:describe_version).and_call_original
      allow(server.auth_chain).to receive(:authenticate).and_call_original

      get path

      expect(last_response).to be_ok
      expect(last_response.headers['Content-Type']).to include('text/html')
      expect(last_response.headers['Cache-Control']).to eq('private, no-store')
      expect(last_response.body).to include(heading, 'aria-label="Breadcrumb"',
                                            'href="/"', 'href="/doc"', 'href="/v1/?page=resources"')
      expect_neutral_shell(last_response.body, 'guide')
      breadcrumb = last_response.body.match(%r{<nav aria-label="Breadcrumb">(.*?)</nav>}m)[1]
      expect(breadcrumb).to include('API versions', 'HaveAPI internals')
      expect(breadcrumb.scan(/<li\b/).length).to eq(path.match?(%r{\A/doc(?:/(?:index(?:\.md)?|readme))?\z}) ? 2 : 3)
      expect(server).not_to have_received(:describe)
      expect(server).not_to have_received(:describe_version)
      expect(server.auth_chain).not_to have_received(:authenticate)
    end
  end

  it 'renders the real README for every internal landing alias with one sidebar menu' do
    pages = %w[/doc /doc/index /doc/index.md /doc/readme].map do |path|
      get path
      body = last_response.body
      main = body.match(%r{<main\b[^>]*>(.*?)</main>}m)[1]
      expect(main).to include('<h1', '>HaveAPI</h1>', 'Server-side implementation', 'Server framework features',
                              '<pre><code class="ruby">', 'class User &lt; ActiveRecord::Base')
      expect(body).to include('<title>HaveAPI internals · ')
      expect(main).not_to include('href="/doc/protocol"', 'href="/doc/client-examples"')
      expect(main.scan('HaveAPI internals').length).to eq(1)
      menu = body.match(%r{<nav aria-label="Shared documentation">(.*?)</nav>}m)[1]
      expect(menu).to include('<h2><a href="/doc">HaveAPI internals</a></h2>')
      expect(menu).not_to include('>Overview</a>')
      expect(menu).not_to include('href="/doc/readme"')
      %w[protocol json-schema create-client client-examples].each do |article|
        expect(menu.scan("href=\"/doc/#{article}\"").length).to eq(1)
      end
      main
    end
    expect(pages.uniq.length).to eq(1)
  end

  it 'uses configured escaped identity or the actual host and port in neutral titles and brand' do
    server = HaveAPI::Server.new(get_opt(:api_module))
    server.use_version(1)
    server.documentation_name = '<API & site>'
    server.mount('/')
    request = Rack::MockRequest.new(server.app)
    %w[/ /doc /doc/protocol].each do |path|
      response = request.get(path, 'HTTP_HOST' => 'example.test:4567')
      expect(response.status).to eq(200)
      expect(response.body).to include('href="/">&lt;API &amp; site&gt;</a>', ' · &lt;API &amp; site&gt;</title>')
      expect(response.body).not_to include('<API & site>')
    end
    fallback = HaveAPI::Server.new(get_opt(:api_module))
    fallback.use_version(1)
    fallback.mount('/')
    response = Rack::MockRequest.new(fallback.app).get('/doc/protocol', 'HTTP_HOST' => 'example.test:4567')
    expect(response.body).to include('href="/">example.test:4567</a>', ' · example.test:4567</title>')
  end

  %w[protocol create-client json-schema].each do |name|
    it "uses actual heading IDs for every #{name} TOC target" do
      get "/doc/#{name}"
      body = last_response.body
      headings = body.scan(/<h[1-6]\b[^>]*\bid="([^"]+)"/).flatten
      navigation = body.match(%r{<nav[^>]*data-action-nav[^>]*>(.*?)</nav>}m)[1]
      targets = navigation.scan(/href="#([^"]+)"/).flatten
      expect(targets).not_to be_empty
      expect(targets - headings).to eq([])
    end
  end

  it 'keeps semantic shared tables in keyboard-accessible overflow regions without changing their cells' do
    get '/doc/performance'
    tables = last_response.body.scan(%r{<table\b[^>]*>.*?</table>}m)
    expect(tables).not_to be_empty
    tables.each do |table|
      expect(last_response.body).to include(%(<div class="docs-table-scroll" role="region" aria-label="Documentation table" tabindex="0">#{table}</div>))
    end
    expect(last_response.body).to include('<th>Measurement policy</th>')
  end

  it 'keeps missing documents and unsupported aliases at 404' do
    %w[/doc/missing /doc/missing.md /doc/readme.md /doc/json-schema.md].each do |path|
      get path
      expect(last_response.status).to eq(404), path
    end
  end

  it 'escapes version labels and links from the existing index description' do
    app
    server = instance_variable_get(:@api)
    label = '<script>version</script>'
    help = '/v1/" onclick="unsafe'
    allow(server).to receive(:describe).and_return(versions: { label => { help: } }, default_version: label)
    get '/'
    expect(last_response.body).to include('Version &lt;script&gt;version&lt;/script&gt;', 'href="/v1/&quot; onclick=&quot;unsafe"')
    expect(last_response.body).not_to include(label, 'href="/v1/" onclick="unsafe"')
  end

  it 'keeps shared and root links mounted under both the API and Rack prefixes' do
    server = HaveAPI::Server.new(get_opt(:api_module))
    server.use_version(1)
    server.mount('/api/')
    request = Rack::MockRequest.new(server.app)
    %w[/api/ /api/doc/protocol].each do |path|
      response = request.get(path, 'HTTP_HOST' => 'example.test', 'SCRIPT_NAME' => '/rack')
      expect(response.status).to eq(200)
      expect(response['Cache-Control']).to eq('private, no-store')
      expect(response.body).to include('href="/rack/api/"', 'href="/rack/api/doc"',
                                       'href="/rack/api/v1/"', 'href="/rack/api/v1/?page=resources"',
                                       'src="/rack/js/documentation.js"')
      expect(response.body).not_to include('href="/doc"', 'href="/v1/"')
    end
  end

  it 'keeps guides anonymous and omits Account when documentation OAuth is not configured' do
    server = HaveAPI::Server.new(get_opt(:api_module))
    server.use_version(1)
    server.mount('/api/')
    allow(server).to receive(:describe).and_call_original
    allow(server).to receive(:describe_version).and_call_original
    allow(server.auth_chain).to receive(:authenticate).and_call_original
    response = Rack::MockRequest.new(server.app).get('/api/doc/protocol', 'HTTP_HOST' => 'example.test')
    expect(response.status).to eq(200)
    expect(response.body).not_to include('aria-label="Account"')
    expect(response.body).not_to include('data-account-menu', 'data-documentation-login', 'docs-visibility-note')
    expect(server).not_to have_received(:describe)
    expect(server).not_to have_received(:describe_version)
    expect(server.auth_chain).not_to have_received(:authenticate)
    get '/doc/protocol'
    expect(last_response.body).not_to include('aria-label="Account"', 'data-account-menu')
  end

  context 'with documentation OAuth configured' do
    it 'offers a neutral Account link without authenticating or describing even with a real session cookie' do
      require_relative '../../test_support/documentation_oauth_fixture'
      server = HaveAPI::Server.new(self.class.const_get(:ApiModule))
      server.use_version(1)
      user = Struct.new(:login).new('guide-user')
      fixture = DocumentationOAuthFixture.configure(server, users: { 1 => { 'guide-token' => user } }, mount_path: '/api/')
      server.mount('/api/')
      allow(server).to receive(:describe).and_call_original
      allow(server).to receive(:describe_version).and_call_original
      allow(server.auth_chain).to receive(:authenticate).and_call_original
      cookie = fixture.header_for(server, version: 1, token: 'guide-token')
      response = Rack::MockRequest.new(server.app).get("#{fixture.origin}/api/doc/protocol",
                                                       'HTTP_HOST' => URI(fixture.origin).host, 'HTTP_COOKIE' => cookie)
      expect(response.status).to eq(200)
      expect(response.body).to include('href="/api/v1/?page=authentication" aria-label="Account"')
      expect(response.body).not_to include('guide-user', 'data-documentation-login', 'docs-visibility-note')
      expect(fixture.lookups).to be_empty
      expect(server).not_to have_received(:describe)
      expect(server).not_to have_received(:describe_version)
      expect(server.auth_chain).not_to have_received(:authenticate)
    end
  end
end
