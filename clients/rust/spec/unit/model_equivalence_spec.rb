require 'spec_helper'
require_relative '../documentation/model_equivalence'

describe RustModelEquivalence do
  it 'does not run generation or baseline source reads when loaded by quick specs' do
    expect(described_class::BASE).to eq('4dc0f7e11c494d1a0dc852dabcc312411699fcab')
    schema = described_class.fixture
    actions = schema.fetch('description').fetch('resources').fetch('widget').fetch('actions')
    expect(actions.keys).to eq(%w[update index])
    expect(actions.fetch('update').fetch('input').fetch('parameters').values.map { |field| field.fetch('type') })
      .to eq(%w[String Text Datetime Integer Float Boolean Custom Resource])
  end

  it 'permits only generator source identity to differ in ownership metadata' do
    Dir.mktmpdir('rust-model-compare-') do |directory|
      roots = %w[baseline candidate].map { |name| File.join(directory, name) }
      manifest = { 'owner' => 'haveapi-rust-client', 'schema_sha256' => 'same fixture', 'generator_source_sha256' => 'a' * 64,
                   'files' => { 'mod.rs' => Digest::SHA256.hexdigest('same generated bytes') } }
      roots.each_with_index do |root, index|
        FileUtils.mkdir_p(root)
        File.write(File.join(root, 'mod.rs'), 'same generated bytes')
        File.write(File.join(root, '.haveapi-generated.json'), JSON.generate(manifest.merge('generator_source_sha256' => (index == 0 ? 'a' : 'b') * 64)))
      end
      expect(described_class.compare(*roots).fetch('owned_file_count')).to eq(1)
      File.write(File.join(roots.last, 'mod.rs'), 'changed generated bytes')
      expect { described_class.compare(*roots) }.to raise_error(RuntimeError, /Generated bytes differ/)
      File.write(File.join(roots.last, 'mod.rs'), 'same generated bytes')
      File.write(File.join(roots.last, '.haveapi-generated.json'), JSON.generate(manifest.merge('schema_sha256' => 'unexpected fixture')))
      expect { described_class.compare(*roots) }.to raise_error(RuntimeError, /ownership metadata/)
    end
  end
end
