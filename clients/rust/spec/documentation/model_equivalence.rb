require 'haveapi/rust_client'
require 'rubygems/package'
require 'rbconfig'
require 'stringio'

# Post-review generation-only comparison. It does not compile or install SDKs.
module RustModelEquivalence
  BASE = '4dc0f7e11c494d1a0dc852dabcc312411699fcab'.freeze

  module_function

  def fixture
    parameter = ->(type) { { 'type' => type, 'required' => false, 'nullable' => false, 'protected' => false } }
    io = ->(parameters, layout = 'object') { { 'parameters' => parameters, 'namespace' => 'widget', 'layout' => layout } }
    fields = %w[String Text Datetime Integer Float Boolean Custom Resource].to_h do |type|
      [type.downcase, parameter.call(type)]
    end
    metadata = io.call({ 'count' => parameter.call('Integer') })
    update = {
      'path' => '/v1.0/widgets/{widget_id}', 'method' => 'PUT', 'aliases' => [], 'auth' => false,
      'input' => io.call(fields), 'output' => io.call(fields),
      'meta' => { 'global' => { 'output' => metadata }, 'object' => { 'output' => metadata } }
    }
    index = update.merge('path' => '/v1.0/widgets/', 'method' => 'GET',
                         'input' => { 'parameters' => {} }, 'output' => io.call(fields, 'object_list'))
    HaveAPI::RustClient::Snapshot.from_description(
      api_version: '1.0', protocol_version: '2.0', source_url: 'https://example.test/v1.0/',
      profile: 'model-equivalence', description: {
        'help' => '/v1.0/', 'meta' => { 'namespace' => '_meta' }, 'authentication' => {},
        'resources' => { 'widget' => { 'resources' => {}, 'actions' => { 'update' => update, 'index' => index } } }
      }
    )
  end

  def files(directory)
    Dir.chdir(directory) { Dir.glob('**/*', File::FNM_DOTMATCH).select { |path| File.file?(path) }.sort }
  end

  def compare(baseline, candidate)
    paths = files(baseline)
    raise 'Generated path set differs from baseline' unless paths == files(candidate)

    marker = HaveAPI::RustClient::Generator::OWNER_FILE
    (paths - [marker]).each do |path|
      unless File.binread(File.join(baseline, path)) == File.binread(File.join(candidate, path))
        raise "Generated bytes differ from baseline: #{path}"
      end
    end
    manifests = [baseline, candidate].map { |directory| JSON.parse(File.read(File.join(directory, marker))) }
    manifests.each do |manifest|
      unless manifest['generator_source_sha256'].is_a?(String) && manifest['generator_source_sha256'].match?(/\A[0-9a-f]{64}\z/)
        raise 'Missing generator source identity'
      end
    end
    comparable = manifests.map { |manifest| manifest.except('generator_source_sha256') }
    raise 'Unexpected ownership metadata difference' unless comparable.first == comparable.last

    { 'owned_file_count' => paths.length - 1, 'baseline_manifest' => manifests.first, 'candidate_manifest' => manifests.last,
      'files_sha256' => (paths - [marker]).to_h { |path| [path, Digest::SHA256.file(File.join(candidate, path)).hexdigest] } }
  end

  def extract_baseline(repository, destination)
    inputs = %w[clients/rust/lib clients/rust/template clients/rust/runtime/src/runtime clients/rust/Gemfile.lock]
    archive, error, status = Open3.capture3('git', 'archive', BASE, *inputs, chdir: repository)
    raise "Baseline source read failed: #{error}" unless status.success?

    Gem::Package::TarReader.new(StringIO.new(archive)) do |tar|
      tar.each do |entry|
        path = entry.full_name
        next if path == 'pax_global_header' && entry.header.typeflag == 'g'
        next if entry.directory? && path == 'clients/'

        unless path.start_with?('clients/rust/') && !path.split('/').include?('..') && (entry.file? || entry.directory?)
          raise 'Unexpected canonical source archive entry'
        end

        target = File.join(destination, path)
        if entry.directory?
          FileUtils.mkdir_p(target)
        else
          FileUtils.mkdir_p(File.dirname(target))
          File.binwrite(target, entry.read)
        end
      end
    end
    File.join(destination, 'clients/rust')
  end

  def generate(component:, output:, schema_path:, config_path:, log:)
    consumer = <<~RUBY
      component = ARGV.shift
      require File.join(component, 'lib/haveapi/rust_client')
      raise 'Generator loaded from the wrong source root' unless HaveAPI::RustClient::Generator::ROOT == component
      schema = JSON.parse(File.read(ARGV.fetch(0)))
      config = JSON.parse(File.read(ARGV.fetch(1)))
      HaveAPI::RustClient::Generator.new(schema:, config:).generate(output: ARGV.fetch(2))
    RUBY
    stdout, stderr, status = Open3.capture3(RbConfig.ruby, '-r', 'bundler/setup', '-e', consumer,
                                            component, schema_path, config_path, output)
    File.write("#{log}.stdout", stdout)
    File.write("#{log}.stderr", stderr)
    raise 'Fixture generation failed; see retained generation logs' unless status.success?
  end

  def run
    raise 'Set HAVEAPI_RUST_MODEL_EQUIVALENCE=1 after final review' unless ENV['HAVEAPI_RUST_MODEL_EQUIVALENCE'] == '1'

    destination = File.expand_path(ENV.fetch('HAVEAPI_RUST_MODEL_EVIDENCE'))
    Dir.mkdir(destination)
    repository = File.expand_path('../../../..', __dir__)
    baseline = extract_baseline(repository, File.join(destination, 'baseline-source'))
    formatter = ENV.fetch('RUSTFMT', 'rustfmt')
    version, status = Open3.capture2(formatter, '--version')
    raise 'Selected formatter identity failed' unless status.success?

    config = { 'crate_name' => 'model-fixture', 'crate_version' => '0.1.0', 'license' => 'MIT', 'edition' => '2024',
               'rust_version' => '1.95', 'rustfmt_version' => version.strip }
    schema_path = File.join(destination, 'snapshot.json')
    config_path = File.join(destination, 'config.json')
    File.write(schema_path, HaveAPI::RustClient::Snapshot.canonical(fixture))
    File.write(config_path, JSON.pretty_generate(config))
    current = File.join(repository, 'clients/rust')
    [baseline, current, current].zip(%w[baseline candidate repeat]).each do |component, name|
      generate(component:, output: File.join(destination, name), schema_path:, config_path:, log: File.join(destination, name))
    end
    result = compare(File.join(destination, 'baseline'), File.join(destination, 'candidate'))
    repeat = compare(File.join(destination, 'candidate'), File.join(destination, 'repeat'))
    unless repeat.fetch('baseline_manifest') == repeat.fetch('candidate_manifest')
      raise 'Candidate generation metadata is nondeterministic'
    end

    File.write(File.join(destination, 'comparison.json'), "#{JSON.pretty_generate(result.merge('baseline_commit' => BASE))}\n")
    $stdout.puts "Generated model equivalence and determinism passed (#{result.fetch('owned_file_count')} owned files)"
  end
end

RustModelEquivalence.run if $0 == __FILE__
